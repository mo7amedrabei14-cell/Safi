/// Short-lived lifetime of a single-use Desktop-to-Website billing handoff (180 seconds).
pub const BILLING_HANDOFF_TTL_SECS: i64 = 180;
/// Lifetime of a scoped Website Billing Portal session (`sfb_*`: 30 minutes).
pub const BILLING_WEB_SESSION_TTL_SECS: i64 = 30 * 60;
/// Token prefix for Website Billing Portal sessions (strictly separated from `sfs_*` and `sfw_*`).
pub const BILLING_WEB_TOKEN_PREFIX: &str = "sfb_";
/// Opaque single-use handoff code prefix.
pub const BILLING_HANDOFF_CODE_PREFIX: &str = "sfbh_";

#[derive(Debug, Clone, Deserialize)]
pub struct StartBillingHandoffRequest {
    pub product: CheckoutProduct,
    #[serde(default)]
    pub seats: Option<u32>,
    #[serde(default = "default_country")]
    pub billing_country_iso2: String,
    #[serde(default)]
    pub coupon_code: Option<String>,
    /// Cryptographically random state generated by Desktop (16..=256 URL-safe token chars).
    pub state: String,
}

fn default_country() -> String {
    "US".to_owned()
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StartBillingHandoffResponse {
    pub handoff_id: Uuid,
    pub billing_url: String,
    pub product: CheckoutProduct,
    pub seats: u32,
    pub billing_country_iso2: String,
    pub provider: BillingProvider,
    pub currency: BillingCurrency,
    pub original_amount_minor: u64,
    pub billing_period: &'static str,
    pub expires_at: i64,
}

#[derive(Debug, Clone, Deserialize)]
pub struct RedeemBillingHandoffRequest {
    pub handoff_code: String,
    pub state: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RedeemedBillingHandoff {
    pub handoff_id: Uuid,
    pub user_id: Uuid,
    pub workspace_id: Uuid,
    pub product: CheckoutProduct,
    pub seats: u32,
    pub billing_country_iso2: String,
    pub coupon_code: Option<String>,
    pub provider: BillingProvider,
    pub currency: BillingCurrency,
    pub original_amount_minor: u64,
    pub billing_period: &'static str,
}

#[derive(Debug, Clone)]
struct InMemoryHandoff {
    id: Uuid,
    user_id: Uuid,
    workspace_id: Uuid,
    state_hash: [u8; 32],
    product: CheckoutProduct,
    seats: u32,
    billing_country_iso2: String,
    coupon_code: Option<String>,
    expires_at: i64,
    consumed: bool,
}

#[derive(Debug, Clone)]
struct InMemoryBillingWebSession {
    id: Uuid,
    user_id: Uuid,
    workspace_id: Uuid,
    token_hash: [u8; 32],
    user_agent_hint: String,
    expires_at: i64,
    revoked: bool,
}

#[derive(Default)]
struct HandoffMemoryStore {
    handoffs_by_code_hash: HashMap<[u8; 32], InMemoryHandoff>,
    web_sessions_by_hash: HashMap<[u8; 32], InMemoryBillingWebSession>,
}

/// Authoritative service for Desktop-to-Website billing handoffs and scoped `sfb_*` sessions.
#[derive(Clone, Default)]
pub struct BillingHandoffService {
    store: Arc<RwLock<HandoffMemoryStore>>,
    pg_store: Option<PgControlPlaneStore>,
    require_durable_pg: bool,
}

impl std::fmt::Debug for BillingHandoffService {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("BillingHandoffService")
            .field("pg_backed", &self.pg_store.is_some())
            .field("require_durable_pg", &self.require_durable_pg)
            .finish()
    }
}

fn random_hex(num_bytes: usize) -> Result<String, AuthError> {
    let mut buf = vec![0u8; num_bytes];
    SystemRandom::new()
        .fill(&mut buf)
        .map_err(|_| AuthError::BackendUnavailable)?;
    Ok(hex::encode(buf))
}

fn blake3_32(raw: &str) -> [u8; 32] {
    *blake3::hash(raw.as_bytes()).as_bytes()
}

fn is_valid_token_chars(raw: &str) -> bool {
    raw.bytes()
        .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

#[must_use]
pub const fn billing_period_for(product: CheckoutProduct) -> &'static str {
    match product {
        CheckoutProduct::IndividualMonthly => "monthly",
        CheckoutProduct::IndividualAnnual | CheckoutProduct::OrganizationSeatAnnual => "annual",
        CheckoutProduct::PayPerFile | CheckoutProduct::CreditPack25 => "one_time",
    }
}

fn normalize_country_iso2(raw: &str) -> Result<String, AuthError> {
    let upper = raw.trim().to_ascii_uppercase();
    if upper.len() != 2 || !upper.bytes().all(|b| b.is_ascii_alphabetic()) {
        return Err(AuthError::InvalidRequest);
    }
    Ok(upper)
}

impl BillingHandoffService {
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    #[must_use]
    pub fn with_pg_store(mut self, pg_store: PgControlPlaneStore) -> Self {
        self.pg_store = Some(pg_store);
        self
    }

    #[must_use]
    pub fn with_require_durable_pg(mut self, required: bool) -> Self {
        self.require_durable_pg = required;
        self
    }

    fn ensure_backend(&self) -> Result<(), AuthError> {
        if self.require_durable_pg && self.pg_store.is_none() {
            return Err(AuthError::BackendUnavailable);
        }
        Ok(())
    }

    /// Step 1 (Authenticated Desktop -> Backend): mint a short-lived (180s), single-use
    /// billing handoff code bound strictly to `(user_id, workspace_id)` and return the official
    /// `/billing?handoff=sfbh_...&state=...` URL (zero session tokens in URL).
    pub async fn start_handoff_at(
        &self,
        user_id: Uuid,
        workspace_id: Uuid,
        req: &StartBillingHandoffRequest,
        public_web_origin: &str,
        now_secs: i64,
    ) -> Result<StartBillingHandoffResponse, AuthError> {
        self.ensure_backend()?;
        let state = req.state.trim();
        if state.len() < 16 || state.len() > 256 || !is_valid_token_chars(state) {
            return Err(AuthError::InvalidRequest);
        }
        let seats = req.seats.unwrap_or(1);
        if req.product == CheckoutProduct::OrganizationSeatAnnual && seats < rules().org_min_seats {
            return Err(AuthError::OrgMinSeatsRequired);
        }
        if seats == 0 || seats > 10_000 {
            return Err(AuthError::InvalidRequest);
        }
        let country = normalize_country_iso2(&req.billing_country_iso2)?;
        let coupon = req
            .coupon_code
            .as_deref()
            .map(|c| c.trim().to_ascii_uppercase())
            .filter(|c| !c.is_empty());
        if coupon.as_deref().is_some_and(|c| c.len() > 64) {
            return Err(AuthError::InvalidRequest);
        }

        let (provider, currency, original_amount_minor) =
            resolve_provider_and_price(&country, req.product, seats);
        let handoff_id = Uuid::now_v7();
        let raw_code = format!("{BILLING_HANDOFF_CODE_PREFIX}{}", random_hex(24)?);
        let code_hash = blake3_32(&raw_code);
        let state_hash = blake3_32(state);
        let expires_at = now_secs + BILLING_HANDOFF_TTL_SECS;

        if let Some(ref pg) = self.pg_store {
            let mut tx = pg
                .pool()
                .begin()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            sqlx::query("SELECT set_config('app.owner_override', 'true', true)")
                .execute(&mut *tx)
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            sqlx::query(
                r"
                INSERT INTO desktop_billing_handoffs (
                    id, user_id, workspace_id, handoff_code_hash, state_hash,
                    product_code, seats, billing_country_iso2, coupon_code, expires_at
                )
                VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9, to_timestamp($10))
                ",
            )
            .bind(handoff_id)
            .bind(user_id)
            .bind(workspace_id)
            .bind(code_hash.as_slice())
            .bind(state_hash.as_slice())
            .bind(req.product.as_str())
            .bind(i32::try_from(seats).unwrap_or(1))
            .bind(&country)
            .bind(&coupon)
            .bind(expires_at)
            .execute(&mut *tx)
            .await
            .map_err(|_| AuthError::BackendUnavailable)?;
            tx.commit()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
        } else {
            self.store.write().await.handoffs_by_code_hash.insert(
                code_hash,
                InMemoryHandoff {
                    id: handoff_id,
                    user_id,
                    workspace_id,
                    state_hash,
                    product: req.product,
                    seats,
                    billing_country_iso2: country.clone(),
                    coupon_code: coupon,
                    expires_at,
                    consumed: false,
                },
            );
        }

        let origin = public_web_origin.trim().trim_end_matches('/');
        let billing_url = format!("{origin}/billing?handoff={raw_code}&state={state}");
        Ok(StartBillingHandoffResponse {
            handoff_id,
            billing_url,
            product: req.product,
            seats,
            billing_country_iso2: country,
            provider,
            currency,
            original_amount_minor,
            billing_period: billing_period_for(req.product),
            expires_at,
        })
    }

    /// Step 2 (Authenticated Website `/billing` -> Backend): atomically verify & consume a single-use
    /// handoff bound to the exact authenticated `(user_id, workspace_id)`.
    pub async fn redeem_handoff_at(
        &self,
        caller_user_id: Uuid,
        caller_workspace_id: Uuid,
        handoff_code: &str,
        state: &str,
        now_secs: i64,
    ) -> Result<RedeemedBillingHandoff, AuthError> {
        self.ensure_backend()?;
        let code = handoff_code.trim();
        let state = state.trim();
        if !code.starts_with(BILLING_HANDOFF_CODE_PREFIX)
            || code.len() < 24
            || code.len() > 160
            || state.len() < 16
            || state.len() > 256
        {
            return Err(AuthError::DesktopAuthCodeInvalid);
        }
        let code_hash = blake3_32(code);
        let state_hash = blake3_32(state);

        if let Some(ref pg) = self.pg_store {
            let mut tx = pg
                .pool()
                .begin()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            sqlx::query("SELECT set_config('app.owner_override', 'true', true)")
                .execute(&mut *tx)
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;

            let row = sqlx::query(
                r"
                SELECT
                    id, user_id, workspace_id, state_hash, product_code, seats,
                    billing_country_iso2, coupon_code,
                    EXTRACT(EPOCH FROM expires_at)::BIGINT AS expires_at_secs,
                    consumed_at IS NOT NULL AS is_consumed
                FROM desktop_billing_handoffs
                WHERE handoff_code_hash = $1
                FOR UPDATE
                ",
            )
            .bind(code_hash.as_slice())
            .fetch_optional(&mut *tx)
            .await
            .map_err(|_| AuthError::BackendUnavailable)?;

            let Some(row) = row else {
                return Err(AuthError::DesktopAuthCodeInvalid);
            };
            let id: Uuid = row
                .try_get("id")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let uid: Uuid = row
                .try_get("user_id")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let wid: Uuid = row
                .try_get("workspace_id")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let stored_state_hash: Vec<u8> = row
                .try_get("state_hash")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let expires_at: i64 = row
                .try_get("expires_at_secs")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let is_consumed: bool = row
                .try_get("is_consumed")
                .map_err(|_| AuthError::BackendUnavailable)?;

            if is_consumed
                || now_secs >= expires_at
                || stored_state_hash
                    .as_slice()
                    .ct_eq(state_hash.as_slice())
                    .unwrap_u8()
                    != 1
            {
                return Err(AuthError::DesktopAuthCodeInvalid);
            }
            if uid != caller_user_id || wid != caller_workspace_id {
                return Err(AuthError::InsufficientScope);
            }

            let updated = sqlx::query(
                r"
                UPDATE desktop_billing_handoffs
                SET consumed_at = to_timestamp($2)
                WHERE id = $1 AND consumed_at IS NULL
                ",
            )
            .bind(id)
            .bind(now_secs)
            .execute(&mut *tx)
            .await
            .map_err(|_| AuthError::BackendUnavailable)?;
            if updated.rows_affected() != 1 {
                return Err(AuthError::DesktopAuthCodeInvalid);
            }

            let product_str: String = row
                .try_get("product_code")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let product =
                CheckoutProduct::from_str_code(&product_str).ok_or(AuthError::InvalidRequest)?;
            let seats = u32::try_from(row.try_get::<i32, _>("seats").unwrap_or(1)).unwrap_or(1);
            let country: String = row
                .try_get("billing_country_iso2")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let coupon_code: Option<String> = row.try_get("coupon_code").ok().flatten();

            tx.commit()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;

            let (provider, currency, original_amount_minor) =
                resolve_provider_and_price(&country, product, seats);
            return Ok(RedeemedBillingHandoff {
                handoff_id: id,
                user_id: uid,
                workspace_id: wid,
                product,
                seats,
                billing_country_iso2: country,
                coupon_code,
                provider,
                currency,
                original_amount_minor,
                billing_period: billing_period_for(product),
            });
        }

        let mut guard = self.store.write().await;
        let Some(entry) = guard.handoffs_by_code_hash.get_mut(&code_hash) else {
            return Err(AuthError::DesktopAuthCodeInvalid);
        };
        if entry.consumed
            || now_secs >= entry.expires_at
            || entry
                .state_hash
                .as_slice()
                .ct_eq(state_hash.as_slice())
                .unwrap_u8()
                != 1
        {
            return Err(AuthError::DesktopAuthCodeInvalid);
        }
        if entry.user_id != caller_user_id || entry.workspace_id != caller_workspace_id {
            return Err(AuthError::InsufficientScope);
        }
        entry.consumed = true;
        let (provider, currency, original_amount_minor) =
            resolve_provider_and_price(&entry.billing_country_iso2, entry.product, entry.seats);
        Ok(RedeemedBillingHandoff {
            handoff_id: entry.id,
            user_id: entry.user_id,
            workspace_id: entry.workspace_id,
            product: entry.product,
            seats: entry.seats,
            billing_country_iso2: entry.billing_country_iso2.clone(),
            coupon_code: entry.coupon_code.clone(),
            provider,
            currency,
            original_amount_minor,
            billing_period: billing_period_for(entry.product),
        })
    }

    /// Mint a short-lived Website Billing Portal session (`sfb_*`, 30m TTL) WITHOUT counting
    /// against or revoking the user's single active Desktop installation (`sfs_*`).
    pub async fn issue_billing_web_session_at(
        &self,
        user_id: Uuid,
        workspace_id: Uuid,
        user_agent_hint: &str,
        now_secs: i64,
    ) -> Result<(String, Uuid, i64), AuthError> {
        self.ensure_backend()?;
        let session_id = Uuid::now_v7();
        let raw_token = format!("{BILLING_WEB_TOKEN_PREFIX}{}", random_hex(32)?);
        let token_hash = blake3_32(&raw_token);
        let expires_at = now_secs + BILLING_WEB_SESSION_TTL_SECS;
        let ua = user_agent_hint.trim();
        let ua_clean = if ua.is_empty() { "billing-web" } else { ua };

        if let Some(ref pg) = self.pg_store {
            let mut tx = pg
                .pool()
                .begin()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            sqlx::query("SELECT set_config('app.owner_override', 'true', true)")
                .execute(&mut *tx)
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            sqlx::query(
                r"
                INSERT INTO billing_web_sessions (
                    id, user_id, workspace_id, token_hash, user_agent_hint, expires_at
                )
                VALUES ($1, $2, $3, $4, $5, to_timestamp($6))
                ",
            )
            .bind(session_id)
            .bind(user_id)
            .bind(workspace_id)
            .bind(token_hash.as_slice())
            .bind(ua_clean)
            .bind(expires_at)
            .execute(&mut *tx)
            .await
            .map_err(|_| AuthError::BackendUnavailable)?;
            tx.commit()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
        } else {
            self.store.write().await.web_sessions_by_hash.insert(
                token_hash,
                InMemoryBillingWebSession {
                    id: session_id,
                    user_id,
                    workspace_id,
                    token_hash,
                    user_agent_hint: ua_clean.to_owned(),
                    expires_at,
                    revoked: false,
                },
            );
        }

        Ok((raw_token, session_id, expires_at))
    }

    /// Authenticate a Website Billing Portal `sfb_*` token (valid ONLY on billing/entitlement routes).
    pub async fn authenticate_billing_web_session_at(
        &self,
        raw_token: &str,
        now_secs: i64,
    ) -> Result<AuthenticatedSession, AuthError> {
        self.ensure_backend()?;
        let trimmed = raw_token.trim();
        if !trimmed.starts_with(BILLING_WEB_TOKEN_PREFIX) || trimmed.len() < 40 {
            return Err(AuthError::InvalidCredentials);
        }
        let token_hash = blake3_32(trimmed);

        if let Some(ref pg) = self.pg_store {
            let mut tx = pg
                .pool()
                .begin()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            sqlx::query("SELECT set_config('app.owner_override', 'true', true)")
                .execute(&mut *tx)
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            let row = sqlx::query(
                r"
                SELECT
                    id, user_id, workspace_id, user_agent_hint,
                    EXTRACT(EPOCH FROM expires_at)::BIGINT AS expires_at_secs,
                    revoked_at IS NOT NULL AS is_revoked
                FROM billing_web_sessions
                WHERE token_hash = $1
                ",
            )
            .bind(token_hash.as_slice())
            .fetch_optional(&mut *tx)
            .await
            .map_err(|_| AuthError::BackendUnavailable)?;
            tx.commit()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;

            let Some(row) = row else {
                return Err(AuthError::InvalidCredentials);
            };
            let is_revoked: bool = row
                .try_get("is_revoked")
                .map_err(|_| AuthError::BackendUnavailable)?;
            if is_revoked {
                return Err(AuthError::Revoked);
            }
            let expires_at: i64 = row
                .try_get("expires_at_secs")
                .map_err(|_| AuthError::BackendUnavailable)?;
            if now_secs >= expires_at {
                return Err(AuthError::Expired);
            }
            let session_id: Uuid = row
                .try_get("id")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let user_id: Uuid = row
                .try_get("user_id")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let workspace_id: Uuid = row
                .try_get("workspace_id")
                .map_err(|_| AuthError::BackendUnavailable)?;
            let ua: String = row
                .try_get("user_agent_hint")
                .unwrap_or_else(|_| "billing-web".to_owned());

            return Ok(AuthenticatedSession {
                session_id,
                token_hash: hex::encode(token_hash),
                device_name: ua,
                device_installation_key_hash: None,
                expires_at,
                principal: Principal {
                    user_id,
                    workspace_id,
                    scopes: vec![Scope::Read, Scope::Write],
                    auth_method: AuthMethod::Password,
                },
            });
        }

        let guard = self.store.read().await;
        let Some(rec) = guard.web_sessions_by_hash.get(&token_hash) else {
            return Err(AuthError::InvalidCredentials);
        };
        if rec.revoked {
            return Err(AuthError::Revoked);
        }
        if now_secs >= rec.expires_at {
            return Err(AuthError::Expired);
        }
        Ok(AuthenticatedSession {
            session_id: rec.id,
            token_hash: hex::encode(rec.token_hash),
            device_name: rec.user_agent_hint.clone(),
            device_installation_key_hash: None,
            expires_at: rec.expires_at,
            principal: Principal {
                user_id: rec.user_id,
                workspace_id: rec.workspace_id,
                scopes: vec![Scope::Read, Scope::Write],
                auth_method: AuthMethod::Password,
            },
        })
    }

    /// Revoke a Website Billing Portal `sfb_*` session.
    pub async fn revoke_billing_web_session(&self, raw_token: &str) -> Result<(), AuthError> {
        self.ensure_backend()?;
        let trimmed = raw_token.trim();
        if !trimmed.starts_with(BILLING_WEB_TOKEN_PREFIX) {
            return Ok(());
        }
        let token_hash = blake3_32(trimmed);
        if let Some(ref pg) = self.pg_store {
            let mut tx = pg
                .pool()
                .begin()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            sqlx::query("SELECT set_config('app.owner_override', 'true', true)")
                .execute(&mut *tx)
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            sqlx::query("UPDATE billing_web_sessions SET revoked_at = now() WHERE token_hash = $1")
                .bind(token_hash.as_slice())
                .execute(&mut *tx)
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            tx.commit()
                .await
                .map_err(|_| AuthError::BackendUnavailable)?;
            return Ok(());
        }
        if let Some(rec) = self
            .store
            .write()
            .await
            .web_sessions_by_hash
            .get_mut(&token_hash)
        {
            rec.revoked = true;
        }
        Ok(())
    }
}
