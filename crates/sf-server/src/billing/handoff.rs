//! Secure Desktop-to-Website Billing Handoff & Scoped Website Billing Sessions (Migration 0016).
//!
//! Security & product invariants:
//! - Desktop NEVER processes card payments; it launches the system browser at the official website's
//!   `/billing?handoff=sfbh_...&state=...` route with a short-lived (180s), single-use opaque code.
//! - ZERO access tokens, refresh tokens, or reusable session credentials ever appear in URLs.
//! - Redeeming a handoff requires an authenticated website user whose `(user_id, workspace_id)`
//!   EXACTLY matches the handoff's creator, verifies `state` in constant time, and atomically marks
//!   the handoff consumed so replays always fail.
//! - Website Billing Sessions (`sfb_*`) expire in 30 minutes, NEVER revoke or count against the
//!   user's single active Desktop installation (`sfs_*`), and are accepted ONLY on billing &
//!   entitlement-read routes.

