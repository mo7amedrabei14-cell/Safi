function formatThemeColorDeclarations(
  palette: Readonly<Record<ColorTokenKey, string>>,
  indent = "  "
): string[] {
  return COLOR_KEYS_ORDER.map((key) => `${indent}${COLOR_CSS_VARS[key]}: ${palette[key]};`);
}

