#!/usr/bin/env python3
"""
tools/gen-errors.py — Deterministic Error Code Generator & Strict CI Verifier (`T1.03`)
Reads `errors.toml` from repository root and generates:
1. Rust error catalog & generated code in `crates/sf-core/src/generated_errors.rs`.
2. TypeScript error catalog, translation keys, and bilingual dictionaries in `packages/i18n/src/generated-errors.ts`.
Also acts as a strict CI verifier (`--check`) ensuring zero unmapped errors exist in Rust or TypeScript source code.
"""

from __future__ import annotations

import argparse
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
try:
    import tomllib
except ImportError:
    try:
        import tomli as tomllib  # type: ignore
    except ImportError:
        print("ERROR [gen-errors]: Python 3.11+ tomllib or tomli is required.", file=sys.stderr)
        sys.exit(1)

ROOT = pathlib.Path(__file__).resolve().parent.parent
ERRORS_TOML = ROOT / "errors.toml"
RUST_GENERATED_RS = ROOT / "crates/sf-core/src/generated_errors.rs"
TS_GENERATED_TS = ROOT / "packages/i18n/src/generated-errors.ts"

VALID_DOMAINS = {
    "IMP", "PRF", "CLN", "CAL", "EXP", "RCP", "CHT",
    "AUTH", "LIC", "PAY", "SYN", "UPD", "AIX", "SYS", "UNK"
}

VALID_SEVERITIES = {"trace", "debug", "info", "warn", "error", "fatal"}


def parse_errors_toml() -> dict[str, dict[str, str]]:
    if not ERRORS_TOML.exists():
        print(f"ERROR [gen-errors]: Missing {ERRORS_TOML}", file=sys.stderr)
        sys.exit(1)

    try:
        data = tomllib.loads(ERRORS_TOML.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"ERROR [gen-errors]: Failed to parse errors.toml: {e}", file=sys.stderr)
        sys.exit(1)

    errors = {}
    for code_str, entry in sorted(data.items()):
        # Validate format SF-<DOMAIN>-<NNN>
        m = re.match(r"^SF-([A-Z]+)-(\d{3})$", code_str)
        if not m:
            print(f"ERROR [gen-errors]: Invalid error code key '{code_str}' in errors.toml (must be SF-<DOMAIN>-<NNN>).", file=sys.stderr)
            sys.exit(1)
        domain, num_str = m.groups()
        if domain not in VALID_DOMAINS:
            print(f"ERROR [gen-errors]: Unknown domain '{domain}' in error code '{code_str}'.", file=sys.stderr)
            sys.exit(1)

        severity = entry.get("severity", "").strip().lower()
        if severity not in VALID_SEVERITIES:
            print(f"ERROR [gen-errors]: Invalid or missing severity '{severity}' for '{code_str}'.", file=sys.stderr)
            sys.exit(1)

        for field in ("title_ar", "action_ar", "title_en", "action_en", "owner_note"):
            val = entry.get(field)
            if not isinstance(val, str) or not val.strip():
                print(f"ERROR [gen-errors]: Missing or non-string required field '{field}' for '{code_str}'.", file=sys.stderr)
                sys.exit(1)

        errors[code_str] = {
            "code": code_str,
            "domain": domain,
            "number": int(num_str),
            "severity": severity,
            "title_ar": entry["title_ar"].strip(),
            "action_ar": entry["action_ar"].strip(),
            "title_en": entry["title_en"].strip(),
            "action_en": entry["action_en"].strip(),
            "owner_note": entry["owner_note"].strip(),
        }
    return errors


def generate_rust_code(errors: dict[str, dict[str, str]]) -> str:
    lines = [
        "// @generated by tools/gen-errors.py — DO NOT EDIT MANUALLY.",
        "// Source of truth: errors.toml (Specification Section 15.4)",
        "",
        "use crate::error::{ErrorCode, ErrorDomain, ErrorSeverity};",
        "",
        "/// Official error catalog entry containing metadata, bilingual messages, and owner notes.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct ErrorCatalogEntry {",
        "    pub code: ErrorCode,",
        "    pub code_str: &'static str,",
        "    pub severity: ErrorSeverity,",
        "    pub title_ar: &'static str,",
        "    pub action_ar: &'static str,",
        "    pub title_en: &'static str,",
        "    pub action_en: &'static str,",
        "    pub owner_note: &'static str,",
        "}",
        "",
        "impl ErrorCode {",
    ]

    for code_str, info in sorted(errors.items()):
        domain = info["domain"]
        num = info["number"]
        const_name = f"SF_{domain}_{num:03d}"
        lines.append(f"    /// Registered error code `{code_str}`.")
        lines.append(f"    pub const {const_name}: Self = Self {{")
        lines.append(f"        domain: ErrorDomain::{domain.capitalize()},")
        lines.append(f"        number: {num},")
        lines.append("    };")

    lines.extend([
        "",
        "    /// Complete array of all officially registered error codes.",
        "    pub const ALL_REGISTERED: &[Self] = &[",
    ])
    for code_str, info in sorted(errors.items()):
        domain = info["domain"]
        num = info["number"]
        lines.append(f"        Self::SF_{domain}_{num:03d},")
    lines.extend([
        "    ];",
        "",
        "    /// Returns `true` if this error code is officially registered in `errors.toml`.",
        "    #[must_use]",
        "    pub fn is_registered(self) -> bool {",
        "        Self::ALL_REGISTERED.contains(&self)",
        "    }",
        "",
        "    /// Returns the official catalog entry for this error code, if registered.",
        "    #[must_use]",
        "    pub fn catalog_entry(self) -> Option<&'static ErrorCatalogEntry> {",
        "        OFFICIAL_ERROR_CATALOG.iter().find(|entry| entry.code == self)",
        "    }",
        "",
        "    /// Returns the official default severity for this error code, if registered.",
        "    #[must_use]",
        "    pub fn default_severity(self) -> Option<ErrorSeverity> {",
        "        self.catalog_entry().map(|e| e.severity)",
        "    }",
        "}",
        "",
        "/// Official error catalog mapping every registered error code to its metadata and messages.",
        "pub const OFFICIAL_ERROR_CATALOG: &[ErrorCatalogEntry] = &[",
    ])

    for code_str, info in sorted(errors.items()):
        domain = info["domain"]
        num = info["number"]
        sev = info["severity"].upper()
        lines.append("    ErrorCatalogEntry {")
        lines.append(f"        code: ErrorCode::SF_{domain}_{num:03d},")
        lines.append(f"        code_str: \"{code_str}\",")
        lines.append(f"        severity: ErrorSeverity::{sev.capitalize()},")
        lines.append(f"        title_ar: {json.dumps(info['title_ar'], ensure_ascii=False)},")
        lines.append(f"        action_ar: {json.dumps(info['action_ar'], ensure_ascii=False)},")
        lines.append(f"        title_en: {json.dumps(info['title_en'], ensure_ascii=False)},")
        lines.append(f"        action_en: {json.dumps(info['action_en'], ensure_ascii=False)},")
        lines.append(f"        owner_note: {json.dumps(info['owner_note'], ensure_ascii=False)},")
        lines.append("    },")

    lines.extend([
        "];",
        "",
    ])
    return "\n".join(lines)


def generate_ts_code(errors: dict[str, dict[str, str]]) -> str:
    code_strs = sorted(errors.keys())
    codes_union = " | ".join([f'"{c}"' for c in code_strs])
    keys_union = " | ".join([f'"error.{c}.title" | "error.{c}.action"' for c in code_strs])

    lines = [
        "// @generated by tools/gen-errors.py — DO NOT EDIT MANUALLY.",
        "// Source of truth: errors.toml (Specification Section 15.4)",
        "",
        f"export type SafiErrorCode = {codes_union};",
        "",
        f"export type SafiErrorTranslationKey = {keys_union};",
        "",
        "export interface SafiErrorCatalogEntry {",
        "  readonly code: SafiErrorCode;",
        "  readonly severity: 'trace' | 'debug' | 'info' | 'warn' | 'error' | 'fatal';",
        "  readonly titleAr: string;",
        "  readonly actionAr: string;",
        "  readonly titleEn: string;",
        "  readonly actionEn: string;",
        "  readonly ownerNote: string;",
        "}",
        "",
        "export const SAFI_ERROR_CODES: readonly SafiErrorCode[] = [",
    ]
    for c in code_strs:
        lines.append(f"  \"{c}\",")
    lines.extend([
        "] as const;",
        "",
        "export const SAFI_ERROR_CATALOG: Record<SafiErrorCode, SafiErrorCatalogEntry> = {",
    ])
    for c, info in sorted(errors.items()):
        lines.append(f"  \"{c}\": {{")
        lines.append(f"    code: \"{c}\",")
        lines.append(f"    severity: \"{info['severity']}\",")
        lines.append(f"    titleAr: {json.dumps(info['title_ar'], ensure_ascii=False)},")
        lines.append(f"    actionAr: {json.dumps(info['action_ar'], ensure_ascii=False)},")
        lines.append(f"    titleEn: {json.dumps(info['title_en'], ensure_ascii=False)},")
        lines.append(f"    actionEn: {json.dumps(info['action_en'], ensure_ascii=False)},")
        lines.append(f"    ownerNote: {json.dumps(info['owner_note'], ensure_ascii=False)},")
        lines.append("  },")
    lines.extend([
        "} as const;",
        "",
        "export const SAFI_ERROR_MESSAGES_AR: Record<string, string> = {",
    ])
    for c, info in sorted(errors.items()):
        lines.append(f"  \"error.{c}.title\": {json.dumps(info['title_ar'], ensure_ascii=False)},")
        lines.append(f"  \"error.{c}.action\": {json.dumps(info['action_ar'], ensure_ascii=False)},")
    lines.extend([
        "} as const;",
        "",
        "export const SAFI_ERROR_MESSAGES_EN: Record<string, string> = {",
    ])
    for c, info in sorted(errors.items()):
        lines.append(f"  \"error.{c}.title\": {json.dumps(info['title_en'], ensure_ascii=False)},")
        lines.append(f"  \"error.{c}.action\": {json.dumps(info['action_en'], ensure_ascii=False)},")
    lines.extend([
        "} as const;",
        "",
        "export function isRegisteredErrorCode(code: string): code is SafiErrorCode {",
        "  return (SAFI_ERROR_CODES as readonly string[]).includes(code);",
        "}",
        "",
        "export function getErrorCatalogEntry(code: SafiErrorCode): SafiErrorCatalogEntry {",
        "  return SAFI_ERROR_CATALOG[code];",
        "}",
        "",
        "export function getErrorLocalizedText(code: SafiErrorCode, locale: 'ar-EG' | 'en-US'): { title: string; action: string } {",
        "  const entry = SAFI_ERROR_CATALOG[code];",
        "  if (locale === 'ar-EG') {",
        "    return { title: entry.titleAr, action: entry.actionAr };",
        "  }",
        "  return { title: entry.titleEn, action: entry.actionEn };",
        "}",
        "",
    ])
    return "\n".join(lines)


def _format_generated(path: pathlib.Path) -> None:
    """Format a generated artifact with the same tool the project gate uses.

    The repository's `make fmt` runs rustfmt and Prettier over the whole tree,
    including generated files. Formatting here keeps `gen-errors --check`
    idempotent instead of flagging a formatter-only difference as drift.
    """
    if path.suffix == ".rs":
        subprocess.run(
            ["rustfmt", "--edition", "2024", str(path)],
            check=False,
            capture_output=True,
            text=True,
        )
        return

    node = shutil.which("node")
    prettier = ROOT / "node_modules" / "prettier" / "bin" / "prettier.cjs"
    if node and prettier.exists():
        subprocess.run(
            [node, str(prettier), "--write", str(path)],
            check=False,
            capture_output=True,
            text=True,
        )


def _formatted_expected(path: pathlib.Path, text: str) -> str:
    """Return generated source after running the project's formatter over it."""
    fd, tmp_name = tempfile.mkstemp(prefix=".gen-errors-", suffix=path.suffix, dir=path.parent)
    tmp_path = pathlib.Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        _format_generated(tmp_path)
        return tmp_path.read_text(encoding="utf-8")
    finally:
        tmp_path.unlink(missing_ok=True)


def do_generate() -> None:
    errors = parse_errors_toml()
    rust_text = generate_rust_code(errors)
    ts_text = generate_ts_code(errors)

    RUST_GENERATED_RS.parent.mkdir(parents=True, exist_ok=True)
    TS_GENERATED_TS.parent.mkdir(parents=True, exist_ok=True)

    RUST_GENERATED_RS.write_text(rust_text, encoding="utf-8")
    TS_GENERATED_TS.write_text(ts_text, encoding="utf-8")
    _format_generated(RUST_GENERATED_RS)
    _format_generated(TS_GENERATED_TS)
    print(f"[gen-errors] Successfully generated {RUST_GENERATED_RS.relative_to(ROOT)} and {TS_GENERATED_TS.relative_to(ROOT)} ({len(errors)} error codes).")


def do_check() -> int:
    errors = parse_errors_toml()
    expected_rust = _formatted_expected(RUST_GENERATED_RS, generate_rust_code(errors))
    expected_ts = _formatted_expected(TS_GENERATED_TS, generate_ts_code(errors))

    violations = []

    if not RUST_GENERATED_RS.exists():
        violations.append(f"Generated Rust file missing: {RUST_GENERATED_RS.relative_to(ROOT)}")
    else:
        current_rust = RUST_GENERATED_RS.read_text(encoding="utf-8")
        if current_rust != expected_rust:
            violations.append(f"Generated Rust file {RUST_GENERATED_RS.relative_to(ROOT)} is out of sync with errors.toml (run python3 tools/gen-errors.py).")

    if not TS_GENERATED_TS.exists():
        violations.append(f"Generated TypeScript file missing: {TS_GENERATED_TS.relative_to(ROOT)}")
    else:
        current_ts = TS_GENERATED_TS.read_text(encoding="utf-8")
        if current_ts != expected_ts:
            violations.append(f"Generated TypeScript file {TS_GENERATED_TS.relative_to(ROOT)} is out of sync with errors.toml (run python3 tools/gen-errors.py).")

    # Source code scan for unmapped error codes (Table 19.7: «فحص CI يفشل لأي خطأ بلا رمز»)
    # Search for pattern SF-[A-Z]+-[0-9]{3} in crates/ and packages/
    registered_codes = set(errors.keys())
    code_pattern = re.compile(r"\bSF-([A-Z]+)-(\d{3})\b")

    search_dirs = [ROOT / "crates", ROOT / "packages", ROOT / "apps"]
    for base in search_dirs:
        if not base.exists():
            continue
        for fpath in base.rglob("*"):
            if not fpath.is_file():
                continue
            if fpath.suffix not in (".rs", ".ts", ".tsx"):
                continue
            parts = fpath.relative_to(ROOT).parts
            if any(p in ("node_modules", "target", "dist") for p in parts):
                continue
            # Skip generated files themselves
            if fpath.name in ("generated_errors.rs", "generated-errors.ts"):
                continue

            try:
                content = fpath.read_text(encoding="utf-8")
            except Exception:
                continue

            for match in code_pattern.finditer(content):
                found_code = match.group(0)
                # Ignore test assertion strings testing parse rejections
                if found_code in ("SF-BAD-001", "SF-IMP-000", "SF-IMP-12", "ERR-IMP-001"):
                    continue
                if found_code not in registered_codes:
                    violations.append(f"Unregistered error code '{found_code}' found in source file {fpath.relative_to(ROOT)} (must be in errors.toml).")

    if violations:
        for v in violations:
            print(f"ERROR [gen-errors --check]: {v}", file=sys.stderr)
        return 1

    print(f"[gen-errors --check] OK: Generated error artifacts match errors.toml and all referenced error codes are valid.")
    return 0


def do_self_test() -> int:
    print("[gen-errors] Running negative self-test suite...")

    # 1. Test invalid code key format in errors.toml simulation
    # 2. Test unmapped error code detection
    dummy_code = "SF-IMP-999"
    code_pattern = re.compile(r"\bSF-([A-Z]+)-(\d{3})\b")
    test_src = f'let err = SafiError::new(ErrorCode::{dummy_code}, ...);'

    registered = set(parse_errors_toml().keys())
    found_unregistered = False
    for m in code_pattern.finditer(test_src):
        c = m.group(0)
        if c not in registered:
            found_unregistered = True

    if not found_unregistered:
        print("FAIL: Self-test failed to detect unregistered error code SF-IMP-999 in source.", file=sys.stderr)
        return 1

    print("[gen-errors] Self-test PASSED successfully.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Deterministic Error Code Generator & CI Verifier")
    parser.add_argument("--generate", action="store_true", help="Generate Rust and TypeScript files from errors.toml")
    parser.add_argument("--check", action="store_true", help="Verify generated files and scan for unmapped error codes")
    parser.add_argument("--self-test", action="store_true", help="Run negative self-tests")
    args = parser.parse_args()

    if args.self_test:
        return do_self_test()
    if args.check:
        return do_check()

    # Default action if no flag or --generate is passed
    do_generate()
    return 0


if __name__ == "__main__":
    sys.exit(main())
